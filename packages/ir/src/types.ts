export type Severity = 'error' | 'warning' | 'info';

export type Diagnostic = {
  severity: Severity;
  /** Stable machine code, e.g. `IR001_UNKNOWN_PORT`, `C202_TYPE_MISMATCH`, `R403_BANDING`. */
  code: string;
  message: string;
  /** Where it happened, when it can be attributed. */
  at?: { node?: string; port?: string; line?: number; column?: number };
  /** Actionable next step for the agent: a hint the patcher can consume directly. */
  fix?: string;
};

/* -------------------------------------------------------------------------- */
/* Patch — the unit of LLM (and optimizer) modification                        */
/* -------------------------------------------------------------------------- */

/**
 * The LLM never rewrites the whole IR. It emits a sequence of ops that are applied
 * and validated against the schema. Small diffs => reviewable, revertible, and the
 * worst case is a rejected patch rather than a corrupted document.
 */
export type PatchOp =
  | {
      op: 'set_param';
      node: string;
      param: string;
      value: ParamValue;
      /** Why — recorded in provenance and shown in the diff UI. */
      reason?: string;
    }
  | { op: 'add_node'; node: ShaderNode; reason?: string }
  | { op: 'remove_node'; node: string; reason?: string }
  /**
   * Replace a node's per-instance body. **`custom_glsl` only** — every other kind's body is a
   * catalog constant, and letting a patch rewrite one would put the six-target guarantee at the
   * mercy of a language model.
   *
   * The text is linted when the document is analysed, exactly like a catalog body, so a banned
   * construct comes back as a diagnostic on the node rather than as a shader that fails to
   * compile in one of six languages.
   */
  | { op: 'set_body'; node: string; body: string; reason?: string }
  | { op: 'connect'; from: WireRef & { node: string }; to: { node: string; port: string }; reason?: string }
  | { op: 'disconnect'; to: { node: string; port: string }; reason?: string }
  | {
      op: 'set_render';
      path: 'qualityTier' | 'maxIterations' | 'resolution' | 'transparent' | 'feedback';
      value: QualityTier | number | [number, number] | boolean;
      reason?: string;
    }
  | { op: 'set_spec'; spec: Partial<ShaderSpec>; reason?: string }
  /**
   * Bind a currently-inline literal to a new named uniform so it becomes tunable.
   *
   * The optional fields here mirror `ParamValue`'s `param` variant exactly, and that
   * symmetry is load-bearing: `inline_param` is defined as the inverse of this op, and an
   * op that could not carry `step`/`group` would make the round trip lossy. The UI reads
   * `step` to size a slider's granularity and `group` to decide which collapsible section
   * the slider lands in — a uniform created by an LLM patch with neither would appear in
   * the wrong place with a wrong-feeling slider, which is exactly the "the tool seems
   * broken" failure mode this project is trying to avoid.
   */
  | {
      op: 'expose_param';
      node: string;
      param: string;
      name: string;
      min?: number;
      max?: number;
      step?: number;
      label?: string;
      group?: string;
      reason?: string;
    }
  /** Inverse of expose_param: fold a uniform back to a literal. */
  | { op: 'inline_param'; node: string; param: string; reason?: string };

export type ShaderPatch = {
  /** Human/agent-readable summary of the whole patch; becomes the undo label. */
  summary: string;
  ops: PatchOp[];
  /** Who proposed it. */
  author?: { kind: 'llm' | 'optimizer' | 'human'; model?: string; round?: number };
};
