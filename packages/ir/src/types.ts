export type NodeKind = (typeof NODE_KINDS)[number];

/** Ports that are considered "the main signal" — used by the GUI to pick a preview wire. */
export type ShaderNode = {
  /** Stable within one IR. `n_uv`, `n_fbm_1`, … Generated by `addNode`, never by an LLM. */
  id: string;
  kind: NodeKind;
  /** Position in the node editor. Purely presentational; ignored by codegen. */
  pos?: { x: number; y: number };
  /** Inline literal values for this node's inputs. Key must exist in the kind's schema. */
  params?: Record<string, ParamValue>;
  /** Inputs wired to other nodes. Key must exist in the kind's schema. */
  inputs?: Record<string, WireRef>;
  /** Free-form annotation surfaced in the UI and to the LLM critic. */
  note?: string;
  /**
   * Per-instance body, replacing the kind's schema template. **`custom_glsl` only.**
   *
   * This is what an escape hatch has to be. Every other kind's body is a constant in the
   * catalog — the whole design rests on that, because a fixed body is what the token rewriter
   * can prove it lowers correctly to six languages. A `custom_glsl` node is the one place
   * where the code is *per instance*, so it cannot live in the schema; it lives here.
   *
   * The text is written in the same **restricted GLSL subset** as the catalog bodies, and
   * `lintSubset` runs over it at document-validation time, so a snippet gets the same
   * treatment as a built-in body: the `${input}` placeholders are expanded by the emitter,
   * `mix_`/`mod_`/`fract_` are renamed per target, matrix products are lowered, and a banned
   * construct is a diagnostic rather than a broken shader in one language.
   *
   * What the subset does **not** check is scope: a snippet may name a helper that does not
   * exist, and that surfaces as a compile error in each target rather than as a silent wrong
   * result. Stated here because it is the one thing the escape hatch cannot promise.
   */
  body?: string;
};

/** A wire endpoint: which node, which output port. */
export type WireRef = {
  node: string;
  /** Defaults to the kind's primary output port when omitted. */
  port?: string;
};

/**
 * A literal value on a node input.
 * `param` binds the value to a **named uniform**, which is the entire basis of
 * fine-tuning: the uniform becomes a slider, and the optimizer searches it.
 */
export type ParamValue =
  | { kind: 'float'; value: number; min?: number; max?: number; step?: number }
  | { kind: 'int'; value: number; min?: number; max?: number }
  | { kind: 'bool'; value: boolean }
  | { kind: 'vec2'; value: [number, number] }
  | { kind: 'vec3'; value: [number, number, number] }
  | { kind: 'vec4'; value: [number, number, number, number] }
  | { kind: 'color'; value: [number, number, number, number] }
  | {
      kind: 'param';
      /** Uniform name, `u_`-prefixed, `[A-Za-z_][A-Za-z0-9_]*`. Unique per IR. */
      name: string;
      /** The type the uniform is declared with in every target. */
      type: ShaderType;
      /** Default / current value. Written into the generated shader as the initializer when a target has no uniform path. */
      value: number | boolean | number[];
      min?: number;
      max?: number;
      step?: number;
      /** Human label for the GUI slider. */
      label?: string;
      /** Grouping in the inspector, e.g. "Noise", "Color". */
      group?: string;
    };

/** Convenience: the concrete runtime shape of a uniform after lowering. */
export type UniformDecl = {
  name: string;
  type: ShaderType;
  value: number | boolean | number[];
  min?: number;
  max?: number;
  step?: number;
  label?: string;
  group?: string;
  /** Where it came from — lets the GUI jump from a slider back to the node. */
  origin: { node: string; param: string };
};

export type ShaderGraph = {
  nodes: ShaderNode[];
  /** Ordered for deterministic emission. Sorted topologically at compile time. */
  edges: Edge[];
};

/** Explicit edge list, derived from `nodes[].inputs`, kept for diffing and UI. */
export type Edge = {
  from: { node: string; port: string };
  to: { node: string; port: string };
};

