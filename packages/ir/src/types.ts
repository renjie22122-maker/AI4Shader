/**
 * AI4Shader — Shader IR (SIR) v1
 * ==============================
 *
 * The SIR is the **single source of truth**. GLSL / WGSL / HLSL / MSL / ShaderLab / UE
 * are all *projections* of this graph. Nothing downstream of the IR holds semantic state.
 *
 * Design constraints (non-negotiable, they are what make the system work):
 *
 *  1. TARGET-AGNOSTIC.  A node never names a shading language, a uniform block, a
 *     texture binding, or a precision qualifier. Those are *lowering* concerns.
 *  2. FULLY SERIALIZABLE.  Plain JSON. It is diffed, hashed, patched, versioned,
 *     sent over the wire, and cached by hash. No closures, no class instances.
 *  3. TYPED PORTS.  Every port has a ShaderType. Type errors are caught statically
 *     before a single line of shader is emitted (cheaper than a compiler round-trip).
 *  4. PARAMS ARE FIRST-CLASS.  Anything a human or an optimizer might want to nudge
 *     is a ParamValue that can be *unbound* into a named uniform. This is what makes
 *     "fine-tuning" a graph rewrite instead of an LLM call.
 *  5. DETERMINISTIC IDS.  Codegen output is a pure function of the IR. Same IR =>
 *     byte-identical shader in every target. This is required for content-addressed
 *     caching of compiled artifacts and golden images.
 *  6. COORDINATE CONVENTION: **GLSL-like everywhere**. Origin bottom-left, uv in
 *     [0,1], RGBA linear (no sRGB) inside the graph. Per-target adapters flip Y
 *     (WGSL/HLSL/MSL write to a top-left-origin target) exactly once, in the
 *     entry-point epilogue, never inside node bodies.
 */

