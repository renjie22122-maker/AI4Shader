/* Node schema (single source of truth for ports, types and GLSL semantics)     */
/* -------------------------------------------------------------------------- */

export type PortSpec = {
  name: string;
  type: ShaderType;
  /** Omitted => derived from the kind's GLSL template. */
  default?: ParamValue;
  label?: string;
};

export type NodeSchema = {
  kind: NodeKind;
  title: string;
  /** Grouping in the node palette. */
  category: 'generator' | 'surface' | 'domain' | 'noise' | 'math' | 'color' | 'output';
  summary: string;
  inputs: PortSpec[];
  outputs: PortSpec[];
  /** Name of the output port considered primary (wire default). */
  primaryOut?: string;
  /**
   * GLSL body. The emitter is a *thunk expander*: it writes this template into a
   * helper function, rewriting identifiers per target. Only a strict, documented
   * subset of GLSL is allowed here so the rewriter is provably correct:
   *
   *   allowed : float/vec2/vec3/vec4/mat2/mat3 literals, + - * / , fns, swizzles,
   *             ternary, if/for with constant bounds, the builtin whitelist below
   *   banned  : precision qualifiers, layout(), samplers, texture(), discard,
   *             #define/#if, arrays, structs, implicit int->float, `mod`, `fract`
   *             (use `fract_`/`mod_` aliases which map per target)
   */
  glsl: string;
  /** Identifier whitelist differences that the rewriter must handle per target. */
  needs?: {
    /** Uses `mat2` constructor — MSL/HLSL adapters need care with row/col major. */
    matrix?: boolean;
    /** Iteration count scales with `render.qualityTier`. */
    qualityScaled?: boolean;
    /** Requires a derivative (dFdx) — unavailable in some WGSL contexts. */
    derivatives?: boolean;
    /**
     * Samples the **host image channel** (`iChannel0` in GLSL/WebGL2, the wired binding
     * elsewhere).
     *
     * What the channel *contains* is the host's decision, so unlike `surface` this is not a
     * contract change to the emitted source — the source is the same either way. It is reported
     * because a host has to *bind* something, and because `render.feedback` only means something
     * when a reachable node actually reads the channel: asking for the previous frame in a
     * document that never samples it is a request that cannot have any effect, and that is worth
     * a diagnostic rather than a shrug.
     */
    channel?: boolean;
    /**
     * Reads a surface host symbol (`iNormal` / `iWorldPos` / `iViewDir` / `iLightDir`).
     *
     * Not a hint — a *contract change*. A node that sets this cannot be evaluated on a
     * fullscreen quad, so when any reachable node sets it the emitters switch to a surface
     * entry point: interpolated vertex outputs instead of `gl_FragCoord`, `uv` from the mesh
     * rather than from the screen, and the light/camera symbols as uniforms the host sets.
     *
     * Kept per-node rather than per-document so that removing the last `normal` node from a
     * graph returns the emission to the quad form exactly — the same discipline as `matrix`,
     * and it is what keeps every existing document byte-identical.
     */
    surface?: boolean;
  };
};

/**
 * Which host symbols the generated shader expects. The runtime harness (WebGL2,
 * WebGPU, Unity, UE, Metal) supplies these; the emitter emits the header that
 * declares them in each language's idiom.
 *
 * ## Screen symbols vs surface symbols
 *
 * The first six describe a *quad*: a resolution, a clock, a pointer, an image. A graph
 * built only from those computes `f(uv, time) -> colour`, which is what this IR was
 * originally able to express.
 *
 * The last five describe a **surface**: which way it faces, where it is, and where the
 * camera and the light are relative to it. A graph that reads any of them is a *shading*
 * graph, and it cannot run on a fullscreen quad — there is no normal to read. Which is why
 * the presence of these is conditional (`NodeSchema.needs.surface`) and changes the entry
 * point every target emits: a quad document still emits a quad shader, byte for byte, while
 * a surface document emits one that takes interpolated vertex outputs.
 *
 * Without these a cel/toon shader — the canonical `quantize(N·L)` — is not merely hard to
 * author, it is unrepresentable: there is no node in the catalog that produces a normal, and
 * a light direction is not a number the graph could invent.
 */
export const HOST_SYMBOLS = [
  'iResolution',
  'iTime',
  'iTimeDelta',
  'iFrame',
  'iMouse',
  'iChannel0',
  'iNormal',
  'iWorldPos',
  'iViewDir',
  'iLightDir',
  'iCameraPos',
] as const;
export type HostSymbol = (typeof HOST_SYMBOLS)[number];

/**
 * The subset that only exists on a surface — declared by the surface entry point, absent from the
 * quad header entirely.
 *
 * Named separately because two things need the list and neither may hardcode it: `analyzeGraph`
 * (to decide that a document is a surface document) and the escape hatch (a `custom_glsl` body is
 * free text, and one that reads `iNormal` needs the surface header even though no node asked for
 * it). `iCameraPos` belongs here rather than with the screen symbols: the quad host never sets it,
 * so declaring it in a quad header would hand the shader a real-looking uniform that is always
 * zero.
 */
export const SURFACE_HOST_SYMBOLS = ['iNormal', 'iWorldPos', 'iViewDir', 'iLightDir', 'iCameraPos'] as const;

